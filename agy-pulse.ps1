    $agyReady = (Test-Path $agyExe) -or ($null -ne (Get-Command agy -ErrorAction SilentlyContinue))
    if (-not $agyReady) {
        Write-Host "==> Installing official Antigravity CLI (agy) for live quota sync..." -ForegroundColor Yellow
        $tmpInstallPs1 = Join-Path $env:TEMP ("agy-cli-install-" + [Guid]::NewGuid().ToString('N') + ".ps1")
        try {
            $cliScript = Invoke-RestMethod -Uri "https://antigravity.google/cli/install.ps1" -TimeoutSec 45
            [System.IO.File]::WriteAllText($tmpInstallPs1, [string]$cliScript, [System.Text.Encoding]::UTF8)
            $psExe = Join-Path $env:SystemRoot "System32\WindowsPowerShell\v1.0\powershell.exe"
            $proc = Start-Process -FilePath $psExe -ArgumentList @('-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', $tmpInstallPs1) -Wait -NoNewWindow -PassThru
            if ($proc.ExitCode -ne 0) {
                Write-Warning "agy CLI installer exited with code $($proc.ExitCode)"
            }
        } catch {
            Write-Warning "Could not auto-install agy CLI: $($_.Exception.Message)"
        } finally {
            if (Test-Path $tmpInstallPs1) {
                Remove-Item -Path $tmpInstallPs1 -Force -ErrorAction SilentlyContinue
            }
        }

        $agyReady = (Test-Path $agyExe) -or ($null -ne (Get-Command agy -ErrorAction SilentlyContinue))
        if (-not $agyReady) {
            Write-Host "  [!] agy CLI is not installed yet (quota display requires it)." -ForegroundColor Yellow
            Write-Host "      Please enable your proxy / TUN mode and re-run this installer, or run:" -ForegroundColor Yellow
            Write-Host "      irm https://antigravity.google/cli/install.ps1 | iex" -ForegroundColor White
        }
    }
}

