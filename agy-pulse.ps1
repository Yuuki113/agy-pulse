function Expand-AgyPulsePayload([string]$gz) {
    $clean = ($gz -replace '\s+', '')
    $gzBytes = [Convert]::FromBase64String($clean)
    $msIn = New-Object System.IO.MemoryStream(,$gzBytes)
    $gzStream = New-Object System.IO.Compression.GZipStream($msIn, [System.IO.Compression.CompressionMode]::Decompress)
    $msOut = New-Object System.IO.MemoryStream
    $gzStream.CopyTo($msOut)
    $gzStream.Dispose()
    $msIn.Dispose()
    $jsonText = [System.Text.Encoding]::UTF8.GetString($msOut.ToArray())
    $msOut.Dispose()
    return ($jsonText | ConvertFrom-Json)
}

function Get-BytesSha256([byte[]]$bytes) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $hash = $sha.ComputeHash($bytes)
    $sha.Dispose()
    return ([BitConverter]::ToString($hash) -replace '-', '').ToLowerInvariant()
}

function Enable-SystemProxyEnv {
    try {
        [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    } catch {}

    try {
        if (-not [string]::IsNullOrWhiteSpace($env:HTTPS_PROXY) -or -not [string]::IsNullOrWhiteSpace($env:https_proxy)) {
            return
        }
        $regPath = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Internet Settings"
        if (-not (Test-Path $regPath)) { return }
        $inet = Get-ItemProperty -Path $regPath -ErrorAction SilentlyContinue
        if ($null -eq $inet) { return }
        $enProp = $inet.PSObject.Properties['ProxyEnable']
        $srvProp = $inet.PSObject.Properties['ProxyServer']
        if ($null -eq $enProp -or $enProp.Value -ne 1 -or $null -eq $srvProp) { return }

        $rawProxy = ([string]$srvProp.Value).Trim()
        if ([string]::IsNullOrWhiteSpace($rawProxy)) { return }

        if ($rawProxy -match 'https=([^;]+)') {
            $rawProxy = $matches[1].Trim()
        } elseif ($rawProxy -match '=([^;]+)') {
            $rawProxy = $matches[1].Trim()
        }
        if ($rawProxy -and $rawProxy -notmatch '^https?://') {
            $rawProxy = "http://$rawProxy"
        }
        if ($rawProxy) {
            if ([string]::IsNullOrWhiteSpace($env:HTTP_PROXY)) { $env:HTTP_PROXY = $rawProxy }
            if ([string]::IsNullOrWhiteSpace($env:HTTPS_PROXY)) { $env:HTTPS_PROXY = $rawProxy }
            Write-Host "  [i] Detected Windows system proxy: $rawProxy" -ForegroundColor DarkGray
        }
    } catch {}
}

function Stop-AgyPulseProcesses {
    $sidecarDataDir = Join-Path $HOME ".gemini\antigravity\sidecar_data\agy-context-ext"
    $hudPidFile = Join-Path $sidecarDataDir "panel\data\hud.pid"
    if (Test-Path $hudPidFile) {
        try {
            $oldHudPid = [int](Get-Content $hudPidFile -ErrorAction Stop).Trim()
            if ($oldHudPid -gt 0 -and $oldHudPid -ne $PID) {
                Stop-Process -Id $oldHudPid -Force -ErrorAction SilentlyContinue
            }
        } catch {}
    }

    $logPath = Join-Path $sidecarDataDir "panel\logs\sidecar.log"
    if (Test-Path $logPath) {
        try {
            $tail = Get-Content $logPath -Tail 12 -ErrorAction Stop
            $portMatch = ($tail | Select-String -Pattern '127\.0\.0\.1:(\d+)' | Select-Object -Last 1)
            if ($portMatch) {
                $port = [int]$portMatch.Matches[0].Groups[1].Value
                $conns = Get-NetTCPConnection -LocalPort $port -State Listen -ErrorAction SilentlyContinue
                foreach ($conn in $conns) {
                    $ownerPid = [int]$conn.OwningProcess
                    if ($ownerPid -gt 0 -and $ownerPid -ne $PID) {
                        $proc = Get-Process -Id $ownerPid -ErrorAction SilentlyContinue
                        if ($proc -and $proc.ProcessName -match '^(Antigravity|node)$') {
                            Stop-Process -Id $ownerPid -Force -ErrorAction SilentlyContinue
                        }
                    }
                }
            }
        } catch {}
    }
}

