if ($DryRunVerify) {
    $count = 0
    foreach ($p in $props) {
        $bytes = [Convert]::FromBase64String([string]$p.Value.b64)
        $actual = Get-BytesSha256 $bytes
        if ($actual -ne [string]$p.Value.sha256) {
            throw "Checksum mismatch on $($p.Name)"
        }
        $count++
    }
    Write-Output "AGY_PULSE_VERIFY_OK ($count files)"
    return
}

